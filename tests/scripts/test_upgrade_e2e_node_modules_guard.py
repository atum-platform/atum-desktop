"""Source-upgrade E2E never runs through a shared node_modules symlink."""

from __future__ import annotations

from pathlib import Path

from tests.e2e.core.upgrade._node_modules_guard import (
    refusal_message,
    symlinked_node_modules,
)


def test_real_directories_are_allowed(tmp_path: Path) -> None:
    (tmp_path / "node_modules").mkdir()
    desktop = tmp_path / "apps" / "desktop" / "node_modules"
    desktop.mkdir(parents=True)

    assert symlinked_node_modules(tmp_path) == ()
    assert refusal_message(tmp_path) is None


def test_shared_dependency_symlinks_are_refused(tmp_path: Path) -> None:
    shared_root = tmp_path / "shared-root"
    shared_desktop = tmp_path / "shared-desktop"
    shared_root.mkdir()
    shared_desktop.mkdir()
    (tmp_path / "node_modules").symlink_to(shared_root, target_is_directory=True)
    desktop = tmp_path / "apps" / "desktop" / "node_modules"
    desktop.parent.mkdir(parents=True)
    desktop.symlink_to(shared_desktop, target_is_directory=True)

    assert symlinked_node_modules(tmp_path) == (
        tmp_path / "node_modules",
        desktop,
    )
    reason = refusal_message(tmp_path)
    assert reason is not None
    assert "source-update npm preparation can empty the shared target" in reason
    assert "node_modules" in reason and "apps/desktop/node_modules" in reason
