"""Refuse destructive source-upgrade E2E against shared dependency symlinks."""

from __future__ import annotations

from pathlib import Path


def symlinked_node_modules(checkout: Path) -> tuple[Path, ...]:
    """Tracked checkout dependency paths an updater test must never mutate."""
    candidates = (
        checkout / "node_modules",
        checkout / "apps" / "desktop" / "node_modules",
    )
    return tuple(path for path in candidates if path.is_symlink())


def refusal_message(checkout: Path) -> str | None:
    linked = symlinked_node_modules(checkout)
    if not linked:
        return None
    rendered = ", ".join(str(path.relative_to(checkout)) for path in linked)
    return (
        "upgrade e2e refuses a checkout whose node_modules is a symlink "
        f"({rendered}); source-update npm preparation can empty the shared target"
    )
