/**
 * The six icon sizes (Atum icon system). Stroke weight is NOT set here — it is a
 * constant rendered width from `--atum-icon-stroke` (styles.css), so never pass
 * `stroke` / `strokeWidth`. Pick the size from the container:
 *   xs 12  close in tabs/chips, 18px badges
 *   sm 14  menu rows, labelled buttons, inline with ≤13.5px text (Button default)
 *   md 16  icon buttons 24–28, list/roster rows, tool steps, search, send
 *   lg 18  window chrome 30, round composer buttons 32
 *   xl 20  dialog glyph tile 44, empty states in cards
 *   2xl 28 page-level empty states
 * Changed from the previous scale: lg 20 → 18, xl 24 → 20, 2xl added.
 */
export const iconSize = {
  xs: 'size-3',
  sm: 'size-3.5',
  md: 'size-4',
  lg: 'size-[1.125rem]',
  xl: 'size-5',
  '2xl': 'size-7'
} as const

export type IconSize = keyof typeof iconSize
