// Atum Kit generator. tokens.json is the only source of --ak-* values; components.css is
// hand-maintained. Emits dist/atum-kit.css (generated token blocks + components.css) and
// dist/atum-kit-tokens.json (the phone's typed projection, shipped through
// packages/mobile-design-exports). `--check` fails, listing the files, when dist/ is stale.
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const PACKAGE = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const OUTPUT = join(PACKAGE, 'dist')

// Desktop and web switch to dark by toggling `.dark` on <html> (themes/appearance.ts
// applyTheme, used by matrix/appearance.tsx applyMatrixPalette); styles.css keys its own
// dark tokens off the same class (`.dark .atum-shell`). The kit's dark tokens follow it.
export const LIGHT_SELECTOR = ':root, .ak-light'
export const DARK_SELECTOR = '.ak-dark, .dark'
export const SCALE_SELECTOR = ':root, .ak-light, .ak-dark'

const HEADER = `/* Atum Kit v0.1 — the one token and component layer for desktop and web.
 * GENERATED by packages/atum-kit/scripts/build.mjs from tokens.json + components.css. Do not edit.
 * The phone mirrors these values in SwiftUI (AtumKit.swift) from dist/atum-kit-tokens.json.
 * Rules:
 *  - Actions are capsules; inputs and containers are rounded rectangles.
 *  - Nested corners are concentric: inner radius = outer radius - padding.
 *  - Colour is rare. Ink carries everything. Red marks danger, failures and mentions;
 *    amber marks a warning, on its icon only. No green, no tinted panels.
 *    Brand colour lives only inside app icons and the user's own content.
 *  - Glass is frosted, for floating chrome only (bars, menus, popovers, toasts). Content stays opaque.
 *  - Focus rings appear for keyboard focus only (:focus-visible).
 *  - The cursor stays an arrow on controls (Mac convention); links in text get the hand.
 * Theme scope: light on :root and .ak-light; dark on .ak-dark and on the desktop's .dark root.
 * color-scheme is set only by the explicit .ak-light / .ak-dark classes, never on bare :root,
 * so the desktop's own color-scheme (set inline by applyTheme) is left alone.
 */
`

/** CSS number without a leading zero, the house style of the approved file (.5, .32). */
const n = value => String(value).replace(/^(-?)0\./, '$1.')
const px = value => `${n(value)}px`
const bezier = points => `cubic-bezier(${points.map(n).join(', ')})`
const without$ = object => Object.fromEntries(Object.entries(object).filter(([key]) => !key.startsWith('$')))

export async function readTokens(path = join(PACKAGE, 'tokens.json')) {
  return JSON.parse(await readFile(path, 'utf8'))
}

/** Every --ak-* declaration, grouped by the block it lives in. Values are CSS strings. */
export function cssDeclarations(tokens) {
  const theme = without$(tokens.theme)
  const mode = name => Object.fromEntries(Object.entries(theme).map(([role, token]) => [role, token[name]]))
  const font = family => `var(--ak-font${family === 'display' ? '-display' : ''})`
  const scale = {
    font: tokens.font.text,
    'font-display': tokens.font.display,
    'font-mono': tokens.font.mono,
    ...Object.fromEntries(Object.entries(tokens.type).map(([role, t]) => [`t-${role}`, `${t.weight} ${px(t.size)}/${px(t.lineHeight)} ${font(t.family)}`])),
    ...Object.fromEntries(Object.entries(tokens.space).map(([step, value]) => [`s${step}`, px(value)])),
    ...Object.fromEntries(Object.entries(tokens.radius).map(([size, value]) => [`r-${size}`, px(value)])),
    ...Object.fromEntries(Object.entries(tokens.controlHeight).map(([size, value]) => [`h-${size}`, px(value)])),
    ...Object.fromEntries(Object.entries(tokens.icon).map(([size, value]) => [`i-${size}`, px(value)])),
    ease: bezier(tokens.motion.ease),
    'ease-in': bezier(tokens.motion['ease-in']),
    ...Object.fromEntries(Object.entries(tokens.motion.duration).map(([step, ms]) => [`dur-${step}`, `${ms}ms`])),
    blur: `blur(${px(tokens.glass.blur)}) saturate(${tokens.glass.saturate}%)`
  }
  for (const [role, token] of Object.entries(theme)) {
    if (typeof token.light !== 'string' || typeof token.dark !== 'string') throw new Error(`Theme token ${role} needs a light and a dark value`)
  }
  return { light: mode('light'), dark: mode('dark'), scale }
}

function block(selector, declarations, notes = {}) {
  const lines = Object.entries(declarations).map(([name, value]) => `  --ak-${name}: ${value};${notes[name] ? ` /* ${notes[name]} */` : ''}`)
  return `${selector} {\n${lines.join('\n')}\n}\n`
}

export function kitCss(tokens, components) {
  const { light, dark, scale } = cssDeclarations(tokens)
  const notes = Object.fromEntries(Object.entries(without$(tokens.theme)).filter(([, token]) => token.$description).map(([role, token]) => [role, token.$description]))
  return [
    HEADER,
    '/* ---------- Tokens (generated from tokens.json) ---------- */\n',
    block(LIGHT_SELECTOR, light, notes),
    block(DARK_SELECTOR, dark, notes),
    block(SCALE_SELECTOR, scale),
    '.ak-light { color-scheme: light; }\n.ak-dark { color-scheme: dark; }\n',
    '\n/* ---------- Components (components.css) ---------- */\n',
    components.endsWith('\n') ? components : `${components}\n`
  ].join('')
}

// ---------- Phone projection ----------

function rgba(value, context) {
  const hex = value.match(/^#([0-9a-f]{6})$/i)
  if (hex) {
    const channel = offset => Number.parseInt(hex[1].slice(offset, offset + 2), 16) / 255
    return { red: channel(0), green: channel(2), blue: channel(4), alpha: 1 }
  }
  const fn = value.match(/^rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)$/)
  if (!fn) throw new Error(`Unsupported colour for ${context}: ${value}`)
  const [red, green, blue] = fn.slice(1, 4).map(part => Number(part) / 255)
  const alpha = Number(fn[4])
  if (![red, green, blue, alpha].every(channel => Number.isFinite(channel) && channel >= 0 && channel <= 1)) throw new Error(`Invalid colour for ${context}`)
  return { red, green, blue, alpha }
}

/** Split on commas that are not inside parentheses. */
function topLevel(value) {
  const parts = []
  let depth = 0
  let start = 0
  for (let index = 0; index < value.length; index++) {
    if (value[index] === '(') depth++
    else if (value[index] === ')') depth--
    else if (value[index] === ',' && depth === 0) { parts.push(value.slice(start, index).trim()); start = index + 1 }
  }
  parts.push(value.slice(start).trim())
  return parts
}

function shadow(value, context) {
  return topLevel(value).map(layer => {
    const color = layer.match(/(rgba\([^)]+\)|#[0-9a-f]{6})$/i)
    if (!color) throw new Error(`Shadow layer without a colour in ${context}: ${layer}`)
    const lengths = layer.slice(0, color.index).trim().split(/\s+/).map(length => {
      const match = length.match(/^(-?[\d.]+)(px)?$/)
      if (!match || (match[1] !== '0' && !match[2])) throw new Error(`Unsupported shadow length in ${context}: ${length}`)
      return Number(match[1])
    })
    if (lengths.length < 3 || lengths.length > 4) throw new Error(`Unsupported shadow layer in ${context}: ${layer}`)
    return { x: lengths[0], y: lengths[1], blur: lengths[2], spread: lengths[3] ?? 0, color: rgba(color[1], context) }
  })
}

function gradient(value, context) {
  const match = value.match(/^linear-gradient\((\d+)deg,\s*(.+)\)$/)
  if (!match) throw new Error(`Unsupported gradient for ${context}: ${value}`)
  const stops = topLevel(match[2])
  return { angleDegrees: Number(match[1]), stops: stops.map((stop, index) => ({ color: rgba(stop, context), location: index / (stops.length - 1) })) }
}

export function phoneTokens(tokens) {
  const theme = without$(tokens.theme)
  const byType = (type, mode, convert) => Object.fromEntries(Object.entries(theme).filter(([, token]) => token.$type === type).map(([role, token]) => [role, convert(token[mode], `${mode} ${role}`)]))
  const unknown = Object.entries(theme).filter(([, token]) => !['color', 'shadow', 'gradient'].includes(token.$type))
  if (unknown.length) throw new Error(`Unknown theme token types: ${unknown.map(([role]) => role).join(', ')}`)
  return {
    schemaVersion: 1,
    kitVersion: tokens.version,
    source: 'packages/atum-kit/tokens.json',
    colorSpace: 'sRGB',
    light: byType('color', 'light', rgba),
    dark: byType('color', 'dark', rgba),
    gradients: { light: byType('gradient', 'light', gradient), dark: byType('gradient', 'dark', gradient) },
    shadows: { light: byType('shadow', 'light', shadow), dark: byType('shadow', 'dark', shadow) },
    type: tokens.type,
    space: tokens.space,
    radius: tokens.radius,
    controlHeight: tokens.controlHeight,
    icon: tokens.icon,
    motion: tokens.motion,
    glass: tokens.glass,
    phone: without$(tokens.phone)
  }
}

/** Same canonical form as packages/mobile-design-exports (sorted keys, two spaces, final newline). */
export function canonicalJSON(value) {
  function canonical(node) {
    if (node === null || typeof node === 'string' || typeof node === 'boolean') return node
    if (typeof node === 'number') { if (!Number.isFinite(node)) throw new Error('Non-finite token number'); return node }
    if (Array.isArray(node)) return node.map(canonical)
    if (node && typeof node === 'object') return Object.fromEntries(Object.keys(node).sort().filter(key => node[key] !== undefined).map(key => [key, canonical(node[key])]))
    throw new Error(`Unsupported token value: ${typeof node}`)
  }
  return `${JSON.stringify(canonical(value), null, 2)}\n`
}

// ---------- Phosphor icons ----------

export const PHOSPHOR_VERSION = '2.1.1'
export const ICON_WEIGHTS = ['light', 'fill']
const SVG = /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 256 256" fill="currentColor">((?:<path d="[^"]+"\/>)+)<\/svg>\s*$/

/** Path data for every icon in icons.json, in each kit weight, read from the pinned @phosphor-icons/core. */
export async function phosphorIcons(names) {
  const require = createRequire(join(PACKAGE, 'package.json'))
  const core = JSON.parse(await readFile(join(dirname(require.resolve('@phosphor-icons/core')), '../package.json'), 'utf8'))
  if (core.version !== PHOSPHOR_VERSION) throw new Error(`Expected @phosphor-icons/core ${PHOSPHOR_VERSION}, found ${core.version}`)
  if (new Set(names).size !== names.length) throw new Error('icons.json lists an icon twice')
  const result = { phosphorVersion: PHOSPHOR_VERSION, viewBox: [0, 0, 256, 256] }
  for (const weight of ICON_WEIGHTS) {
    result[weight] = {}
    for (const name of [...names].sort()) {
      if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) throw new Error(`Invalid Phosphor icon name: ${name}`)
      let source
      try { source = await readFile(require.resolve(`@phosphor-icons/core/${weight}/${name}-${weight}.svg`), 'utf8') } catch { throw new Error(`Unknown Phosphor ${weight} icon: ${name}`) }
      const match = source.match(SVG)
      if (!match) throw new Error(`Unexpected SVG shape for ${weight}/${name}; only <path> icons are supported`)
      result[weight][name] = [...match[1].matchAll(/<path d="([^"]+)"\/>/g)].map(path => path[1])
    }
  }
  return result
}

export async function generate() {
  const [tokens, components, icons] = await Promise.all([readTokens(), readFile(join(PACKAGE, 'components.css'), 'utf8'), readFile(join(PACKAGE, 'icons.json'), 'utf8').then(JSON.parse)])
  if (/--ak-[\w-]+\s*:/.test(components)) throw new Error('components.css must not declare --ak-* tokens; add them to tokens.json')
  return {
    'atum-kit.css': kitCss(tokens, components),
    'atum-kit-tokens.json': canonicalJSON(phoneTokens(tokens)),
    'phosphor-icons.json': canonicalJSON(await phosphorIcons(icons.names))
  }
}

export async function produce({ check = false, output = OUTPUT } = {}) {
  const files = await generate()
  if (check) {
    let present = []
    try { present = await readdir(output) } catch (error) { if (error.code !== 'ENOENT') throw error }
    const current = Object.fromEntries(await Promise.all(present.map(async name => [name, await readFile(join(output, name), 'utf8')])))
    const dirty = [...new Set([...Object.keys(current), ...Object.keys(files)])].filter(name => current[name] !== files[name])
    if (dirty.length) throw new Error(`Atum Kit dist/ is stale: ${dirty.join(', ')}. Run npm run --workspace @atum/kit build and commit dist/.`)
  } else {
    await mkdir(output, { recursive: true })
    for (const [name, text] of Object.entries(files)) await writeFile(join(output, name), text)
  }
  return files
}

if (process.argv[1] === fileURLToPath(import.meta.url)) produce({ check: process.argv.includes('--check') }).catch(error => { console.error(error.message); process.exitCode = 1 })
